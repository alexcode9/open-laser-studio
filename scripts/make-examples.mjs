// Regenerate files in examples/ from the native core (run `pnpm build:native` first).
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const native = createRequire(import.meta.url)(join(root, 'apps/desktop/native/laser_node.node'));
const out = (name) => join(root, 'examples', name);

const cylinder = native.sampleProject();
writeFileSync(out('sample-cylinder.ols'), native.saveOls(cylinder, null));

const flat = { ...cylinder, name: 'Sample — flat field', mode: 'flat' };
// Fit the artwork inside the 115 x 115 mm galvo field.
const placeFlat = {
  'obj-wave': { x: 10, y: 30, scaleX: 0.5, scaleY: 0.5 },
  'obj-disc-1': { x: 25, y: 75 },
  'obj-disc-2': { x: 90, y: 75 },
};
flat.document = {
  ...flat.document,
  objects: flat.document.objects
    .filter((o) => placeFlat[o.id])
    .map((o) => ({ ...o, transform: { ...o.transform, ...placeFlat[o.id] } })),
};
writeFileSync(out('sample-flat.ols'), native.saveOls(flat, null));

const header = '; Generated by Open Laser Studio for inspection only. NOT validated on hardware.\n';
const cylPlan = await native.planToolpath(cylinder);
writeFileSync(out('sample-cylinder-f1.nc'), header + cylPlan.gcodeListing.join('\n') + '\n');
const flatPlan = await native.planToolpath(flat);
writeFileSync(out('sample-flat-f1.nc'), header + flatPlan.gcodeListing.join('\n') + '\n');

console.log('cylinder:', cylPlan.summary.stats.segmentCount, 'segments,', cylPlan.gcodeListing.length, 'G-code lines');
console.log('flat:', flatPlan.summary.stats.segmentCount, 'segments,', flatPlan.gcodeListing.length, 'G-code lines', flatPlan.summary.errors);
